export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { locale } = await params;
  const currentLocale = resolveLocale(locale);
  const copy = getMessages(currentLocale, "LessTimeMarketing");
  const path = localizedPath(currentLocale, PAGE_PATH);
  const image = { url: SOCIAL_MARKETING_ICON, width: SOCIAL_MARKETING_ICON_SIZE, height: SOCIAL_MARKETING_ICON_SIZE, alt: copy.iconAlt };

  return {
    metadataBase: new URL(SITE_URL),
    title: copy.seoTitle,
    description: copy.seoDescription,
    icons: {
      icon: { url: SOCIAL_MARKETING_ICON_SMALL, type: "image/webp" },
      shortcut: SOCIAL_MARKETING_ICON_SMALL,
      apple: SOCIAL_MARKETING_ICON_SMALL,
    },
    alternates: {
      canonical: path,
      languages: { en: PAGE_PATH, es: `/es${PAGE_PATH}`, "x-default": PAGE_PATH },
    },
    openGraph: {
      title: copy.seoTitle,
      description: copy.seoDescription,
      url: `${SITE_URL}${path}`,
      siteName: "ShopiDeck",
      type: "website",
      locale: localeInfo[currentLocale].openGraph,
      alternateLocale: localeInfo[currentLocale].alternateOpenGraph,
      images: [image],
    },
    twitter: { card: "summary", title: copy.seoTitle, description: copy.seoDescription, images: [{ url: SOCIAL_MARKETING_ICON, alt: copy.iconAlt }] },
  };
}

const statusStyles: Record<CellStatus, { Icon: typeof Check; className: string }> = {
  yes: { Icon: Check, className: "bg-app-ink text-white" },
  no: { Icon: X, className: "bg-brand-border/70 text-brand-secondary" },
  partial: { Icon: Minus, className: "bg-brand-accent/40 text-brand-main" },
  unknown: { Icon: CircleHelp, className: "bg-brand-bg text-brand-muted" },
};

function StatusCell({ status, text }: { status: string; text: string }) {
  const { Icon, className } = statusStyles[(status as CellStatus) in statusStyles ? (status as CellStatus) : "unknown"];
  return (
    <span className="flex items-start gap-2.5">
      <span className={`mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded-full ${className}`}>
        <Icon className="h-3 w-3" strokeWidth={3} aria-hidden="true" />
      </span>
      <span>{text}</span>
    </span>
  );
}

